// Scopes the Careers interactions reference stylesheet to the Careers page.
// Input : the reference's src/index.css (humanx-careers-page)
// Output: src/app/careers/careers-ref.css — every selector prefixed with `.hxc`, the motion gate
//         `.js` mapped to `.hxc[data-motion]`, keyframes renamed `hxc-*`, header (`.sh`) and unused
//         sections dropped, fonts mapped to this site's tokens. Cascade order is preserved.
// Usage : node scripts/scope-careers-css.mjs <path-to-reference-index.css>
import fs from "node:fs";
import postcss from "postcss";

const src = process.argv[2];
if (!src) throw new Error("pass the reference index.css path");
const root = postcss.parse(fs.readFileSync(src, "utf8"));

const W = ".hxc";
const DROP = /(^|[\s,>+~(])\.(sh|sh-[\w-]+|site-nav|nav|nav-[\w-]+|lf|lf-[\w-]+|wf|wf-[\w-]+|ft|ft-[\w-]+|menu|mn-[\w-]+)(?![\w-])/;
const kf = new Map();

root.walkAtRules((at) => {
  if (at.name === "import") at.remove();
  else if (/keyframes$/.test(at.name)) {
    const n = "hxc-" + at.params.trim();
    kf.set(at.params.trim(), n);
    at.params = n;
  }
});

function scopeOne(sel) {
  sel = sel.trim();
  if (!sel) return null;
  if (DROP.test(sel)) return null;
  // the motion gate
  sel = sel.replace(/:root:not\(\.js\)/g, `${W}:not([data-motion])`);
  sel = sel.replace(/^html\.js\b/, `${W}[data-motion]`).replace(/^\.js(?![\w-])/, `${W}[data-motion]`);
  sel = sel.replace(/^\.theme-ready(?![\w-])/, `${W}.theme-ready`);
  // html/body/:root become the wrapper itself
  if (/^(:root|html|body)$/.test(sel)) return W;
  sel = sel.replace(/^(:root|html|body)\s+/, "");
  sel = sel.replace(/:is\(html,\s*body,\s*/g, ":is(");
  if (sel.startsWith(W)) return sel;
  return `${W} ${sel}`;
}

root.walkRules((rule) => {
  if (rule.parent?.type === "atrule" && /keyframes$/.test(rule.parent.name)) return;
  const out = rule.selectors.map(scopeOne).filter(Boolean);
  // `*` and element resets on the wrapper's subtree only
  if (!out.length) rule.remove();
  else rule.selectors = [...new Set(out)];
});

root.walkDecls((d) => {
  if (/^animation(-name)?$/.test(d.prop)) {
    for (const [a, b] of kf) d.value = d.value.replace(new RegExp(`(^|[\\s,])${a}(?=$|[\\s,])`, "g"), `$1${b}`);
  }
  if (d.prop === "--sans") d.value = "var(--font-sans)";
  if (d.prop === "--mono") d.value = "var(--font-mono)";
});

// empty at-rules left behind
root.walkAtRules((at) => {
  if (at.nodes && !at.nodes.length) at.remove();
});

const banner = `/* GENERATED by scripts/scope-careers-css.mjs from the Careers interactions reference
   (humanx-careers-page/src/index.css). Careers page only: every selector is scoped to .hxc.
   Edit the reference + regenerate, or override in careers.css. */\n`;
fs.writeFileSync("src/app/careers/careers-ref.css", banner + root.toString());
console.log("rules:", root.nodes.length, "keyframes renamed:", kf.size);
